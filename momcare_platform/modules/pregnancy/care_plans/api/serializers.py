class AdjustmentCreateSerializer(serializers.Serializer):
    section = serializers.ChoiceField(choices=[SECTION_NUTRITION, SECTION_EXERCISE])
    list_name = serializers.CharField(max_length=40)
    action = serializers.ChoiceField(choices=["add", "edit", "remove"])
    item_key = serializers.CharField(max_length=80, required=False, allow_blank=True, default="")
    content = serializers.DictField(required=False, default=dict)


class AdjustmentUpdateSerializer(serializers.Serializer):
    content = serializers.DictField()


class TextSerializer(serializers.Serializer):
    text = serializers.CharField(max_length=2000, trim_whitespace=True)


class ReasonSerializer(serializers.Serializer):
    reason = serializers.CharField(max_length=500, required=False, allow_blank=True, default="")


class AllergiesConditionsSerializer(serializers.Serializer):
    food_allergies = serializers.ListField(child=serializers.CharField(max_length=60), required=False, max_length=30)
    dietary_preference = serializers.ChoiceField(choices=[c[0] for c in DIETARY_PREFERENCE_CHOICES], required=False)

    def get_fields(self):
        fields = super().get_fields()
        for factor in Pregnancy.FACTOR_FIELDS:
            fields[factor] = serializers.ChoiceField(choices=["yes", "no", "unknown"], required=False)
        return fields

    def validate(self, attrs):
        if not attrs:
            raise serializers.ValidationError("Send at least one field to change.")
        return attrs


class GuidanceSerializer(serializers.Serializer):
    guidance = serializers.CharField(max_length=1000)


class OptionalGuidanceSerializer(serializers.Serializer):
    guidance = serializers.CharField(max_length=1000, required=False)
